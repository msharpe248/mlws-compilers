/* mlws-vm-luac: compile a Lua 5.5 program to MLWSVM assembly.
 *
 *   mlws-vm-luac [--shared] [-o FILE] [-n NAME] program.lua    (FILE '-' is standard output)
 *   mlws-vm-luac --library DIR
 *
 * The output is one self-contained MLWSVM assembly file: the program, the
 * runtime and the library. `mlwsvm run` runs it and `mlwsvm asm` turns it
 * into a binary module. With --shared it is the program alone, which
 * imports the runtime and the library from the MLWSVM library lua of this
 * version; --library writes that library's source to DIR (library.masm and
 * lua.masm), for `mlwsvm lib build DIR`. Errors in the program are
 * reported as lua does ("program.lua:3: ... near ..."), with exit status
 * 1. NAME is the chunk name used in messages (default: the path as given). */
#include <errno.h>
#include <stdlib.h>
#include <string.h>

#include "lua.h"

static char *read_file(const char *path, size_t *len) {
    FILE *f = fopen(path, "rb");
    if (!f) {
        fprintf(stderr, "mlws-vm-luac: cannot open %s: %s\n", path, strerror(errno));
        exit(1);
    }
    size_t cap = 65536, n = 0, r;
    char *buf = xmalloc(cap);
    while ((r = fread(buf + n, 1, cap - n - 1, f)) > 0) {
        n += r;
        if (n + 1 == cap)
            buf = xrealloc(buf, cap *= 2);
    }
    fclose(f);
    buf[n] = 0;
    *len = n;
    return buf;
}

/* Write the library's source to dir: its manifest and its module. */
static int write_library(const char *dir) {
    size_t n = strlen(dir);
    char *path = xmalloc(n + 16);
    snprintf(path, n + 16, "%s/library.masm", dir);
    FILE *f = fopen(path, "w");
    if (!f) {
        fprintf(stderr, "mlws-vm-luac: cannot write %s: %s\n", path, strerror(errno));
        return 1;
    }
    fprintf(f, "; The Lua runtime library, generated by mlws-vm-luac %s\n", VERSION);
    fprintf(f, ".library lua, \"%s\"\n.requires mlwsvm, \">=0.4\"\n.public lua\n", VERSION);
    if (fclose(f) != 0) {
        fprintf(stderr, "mlws-vm-luac: cannot write %s\n", path);
        return 1;
    }
    snprintf(path, n + 16, "%s/lua.masm", dir);
    f = fopen(path, "w");
    if (!f) {
        fprintf(stderr, "mlws-vm-luac: cannot write %s: %s\n", path, strerror(errno));
        return 1;
    }
    int ids = 0;
    Func *prelude = parse_chunk("prelude", prelude_lua, strlen(prelude_lua), true, &ids);
    Func *none = parse_chunk("lua", "", 0, false, &ids);
    GenInput in = {"lua", none, prelude, runtime_masm, GEN_LIBRARY, NULL};
    generate(&in, f);
    if (fclose(f) != 0) {
        fprintf(stderr, "mlws-vm-luac: cannot write %s\n", path);
        return 1;
    }
    free(path);
    return 0;
}

static void usage(void) {
    fprintf(stderr, "usage: mlws-vm-luac [--shared] [-o FILE] [-n NAME] program.lua\n"
                    "       mlws-vm-luac --library DIR\n"
                    "  -o FILE        write the assembly to FILE (default: program.masm; '-' for stdout)\n"
                    "  -n NAME        the chunk name in error messages (default: the path)\n"
                    "  --shared       import the runtime from the MLWSVM library lua (lua-%s.mlwsl)\n"
                    "  --library DIR  write the source of that library to DIR\n"
                    "  --version      print the version\n", VERSION);
    exit(2);
}

int main(int argc, char **argv) {
    const char *out = NULL, *path = NULL, *name = NULL, *libdir = NULL;
    bool shared = false;
    for (int i = 1; i < argc; i++) {
        if (strcmp(argv[i], "-o") == 0 && i + 1 < argc)
            out = argv[++i];
        else if (strcmp(argv[i], "--shared") == 0)
            shared = true;
        else if (strcmp(argv[i], "--library") == 0 && i + 1 < argc)
            libdir = argv[++i];
        else if (strcmp(argv[i], "-n") == 0 && i + 1 < argc)
            name = argv[++i];
        else if (strcmp(argv[i], "--version") == 0) {
            printf("mlws-vm-luac %s\n", VERSION);
            return 0;
        }
        else if (argv[i][0] == '-' && argv[i][1])
            usage();
        else if (!path)
            path = argv[i];
        else
            usage();
    }
    if (libdir) {
        if (path || out || shared)
            usage();
        return write_library(libdir);
    }
    if (!path)
        usage();
    if (!name)
        name = path;
    size_t len;
    char *src = read_file(path, &len);
    int ids = 0;
    Func *prelude = parse_chunk("prelude", prelude_lua, strlen(prelude_lua), true, &ids);
    Func *main_fn = parse_chunk(name, src, len, false, &ids);
    char *outpath = NULL;
    if (!out) {
        size_t n = strlen(path);
        outpath = xmalloc(n + 6);
        strcpy(outpath, path);
        char *dot = strrchr(outpath, '.');
        char *slash = strrchr(outpath, '/');
        if (dot && (!slash || dot > slash))
            *dot = 0;
        strcat(outpath, ".masm");
        out = outpath;
    }
    /* a program named lua would be the library's module, and lua.masm
       next to it would be found instead of the library */
    const char *module = NULL;
    if (shared && strcmp(out, "-") != 0) {
        const char *base = strrchr(out, '/') ? strrchr(out, '/') + 1 : out;
        if (strcmp(base, "lua.masm") == 0 || strcmp(base, "lua.mlwso") == 0) {
            fprintf(stderr, "mlws-vm-luac: with --shared, the output cannot be named %s (the library is lua)\n", base);
            return 1;
        }
        if (strncmp(base, "lua.", 4) == 0)
            module = "lua_program";
    }
    FILE *f = strcmp(out, "-") == 0 ? stdout : fopen(out, "w");
    if (!f) {
        fprintf(stderr, "mlws-vm-luac: cannot write %s: %s\n", out, strerror(errno));
        return 1;
    }
    GenInput in = {name, main_fn, prelude, runtime_masm, shared ? GEN_SHARED : GEN_INLINE, module};
    generate(&in, f);
    if (f != stdout && fclose(f) != 0) {
        fprintf(stderr, "mlws-vm-luac: cannot write %s: %s\n", out, strerror(errno));
        return 1;
    }
    return 0;
}
