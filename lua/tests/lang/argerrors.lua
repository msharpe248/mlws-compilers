-- Argument errors name the function as Lua does: by the name at the call
-- site (a method call does not count self), else by its name in the
-- library; "no value" is an argument the call did not pass.
local function e(f, ...)
  local ok, msg = pcall(f, ...)
  print((tostring(msg):gsub("^[^:]*:%d+: ", "")))
end
-- called directly
e(function() return string.rep() end)
e(function() return string.rep("x", nil) end)
e(function() return ("x"):rep() end)
e(function() return ("x"):rep({}) end)
e(function() local r = string.rep; return r() end)
e(function() local t = {f = string.rep}; return t.f() end)
e(function() return select("x") end)
e(function() return setmetatable({}, 1) end)
e(function() return math.floor({}) end)
e(function() return table.insert({}, 1, 2, 3) end)
e(function() return io.write({}) end)
e(function() return io.stdout:write({}) end)
e(function() return string.format("%d", "x") end)
e(function() return string.format("%d", 1.5) end)
e(function() return ("%d"):format() end)
e(function() return string.gsub() end)
e(function() return ("x"):gsub() end)
e(function() return table.concat({{}}) end)
e(function() return table.sort({3, 1}, 1) end)
e(function() return utf8.char(-1) end)
e(function() return utf8.len(1, 5) end)
e(function() return coroutine.resume(1) end)
e(function() return coroutine.status(1) end)
e(function() return os.time(1) end)
e(function() return tonumber("10", 99) end)
e(function() return math.random(2, 1) end)
e(function() return rawlen(1) end)
e(function() return table.unpack(1) end)
e(function() return next(1) end)
e(function() for _ in ipairs() do end end)
e(function() return tostring() end)
-- called by pcall: the library's name
e(string.rep)
e(string.rep, nil)
e(math.sqrt)
e(table.insert, 1, 2)
e(io.write, {})
e(string.format, "%d", "x")
e(string.gsub)
e(string.char, -1)
e(utf8.char, -1)
e(coroutine.resume, 1)
e(os.time, 1)
e(next, 1)
e(rawlen, 1)
e(string.sub)
e(table.unpack, 1)
e(ipairs)
e(tostring)
