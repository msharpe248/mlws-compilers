-module(basics).
-export([main/0]).

main() ->
    io:format("~p~n", [1 + 2 * 3]),
    io:format("~p ~p ~p~n", [7 div 2, 7 rem 2, -7 div 2]),
    io:format("~p ~p~n", [7 / 2, 1 / 4]),
    io:format("~p~n", [1 bsl 10]),
    io:format("~p ~p ~p~n", [5 band 3, 5 bor 3, 5 bxor 3]),
    io:format("~p ~p~n", [bnot 5, -16 bsr 2]),
    io:format("~p~n", [9223372036854775807 + 1]),
    io:format("~p~n", [-9223372036854775808 - 1]),
    io:format("~p~n", [12345678901234567890 * 98765432109876543210]),
    io:format("~p~n", [1 bsl 100]),
    io:format("~p ~p~n", [abs(-5), abs(-2.5)]),
    io:format("~p ~p ~p ~p~n", [trunc(3.7), round(3.5), round(-3.5), float(3)]),
    io:format("~p ~p~n", [1 == 1.0, 1 =:= 1.0]),
    io:format("~p ~p ~p~n", [1 < a, a < {}, {} < []]),
    io:format("~p ~p~n", [[1,2] < [1,3], {1,2} < {1,2,0}]),
    io:format("~p ~p~n", [atom, 'Quoted atom']),
    io:format("~p~n", [{tuple, [list, "of", chars], 3.25}]),
    io:format("~p ~p~n", [length([a,b,c]), tuple_size({1,2})]),
    io:format("~p ~p~n", [hd([x,y]), tl([x,y])]),
    io:format("~p~n", [element(2, {a,b,c})]),
    io:format("~p~n", [setelement(2, {a,b,c}, z)]),
    io:format("~p~n", [[1,2] ++ [3,4]]),
    io:format("~p~n", [[1,2,3,2,1] -- [2,1]]),
    io:format("~p ~p~n", [true andalso false, true orelse false]),
    io:format("~p ~p ~p~n", [not true, true and true, false or true]),
    X = 10,
    Y = X * X,
    io:format("~p~n", [Y]),
    io:format("~p~n", [atom_to_list(hello)]),
    io:format("~p~n", [list_to_atom("world")]),
    io:format("~p ~p~n", [integer_to_list(255), list_to_integer("-42")]),
    io:format("~p~n", [integer_to_list(255, 16)]),
    io:format("~p~n", [tuple_to_list({1,2,3})]),
    io:format("~p~n", [list_to_tuple([a,b])]),
    io:format("~p ~p~n", [max(3, 7), min(3, 7)]),
    io:format("~p~n", [1.0e10]),
    io:format("~p ~p ~p~n", [0.1, 100.0, 1.5e-5]),
    io:format("~p~n", [$a]),
    io:format("~p~n", [[$h, $i]]),
    io:format("~p~n", [is_integer(3) andalso is_float(3.0) andalso is_atom(a)]),
    ok.
