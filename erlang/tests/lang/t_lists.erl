-module(t_lists).
-export([main/0]).

main() ->
    L = [5, 3, 8, 1, 9, 2],
    io:format("~p~n", [lists:sort(L)]),
    io:format("~p~n", [lists:reverse(L)]),
    io:format("~p ~p ~p~n", [lists:sum(L), lists:max(L), lists:min(L)]),
    io:format("~p~n", [lists:nth(3, L)]),
    io:format("~p~n", [lists:last(L)]),
    io:format("~p~n", [lists:member(8, L)]),
    io:format("~p~n", [lists:seq(1, 10, 3)]),
    io:format("~p~n", [lists:seq(10, 1, -2)]),
    io:format("~p~n", [lists:zip([a, b, c], [1, 2, 3])]),
    io:format("~p~n", [lists:unzip([{a, 1}, {b, 2}])]),
    io:format("~p~n", [lists:flatten([1, [2, [3, [4]], 5]])]),
    io:format("~p~n", [lists:append([[1], [2, 3], []])]),
    io:format("~p~n", [lists:keyfind(b, 1, [{a, 1}, {b, 2}])]),
    io:format("~p~n", [lists:keystore(c, 1, [{a, 1}], {c, 3})]),
    io:format("~p~n", [lists:keysort(2, [{x, 3}, {y, 1}, {z, 2}])]),
    io:format("~p~n", [lists:partition(fun(X) -> X > 4 end, L)]),
    io:format("~p~n", [lists:split(2, L)]),
    io:format("~p~n", [lists:sublist(L, 2, 3)]),
    io:format("~p~n", [lists:duplicate(3, x)]),
    io:format("~p~n", [lists:usort([3, 1, 2, 3, 1])]),
    io:format("~p~n", [lists:all(fun is_integer/1, L)]),
    io:format("~p~n", [lists:any(fun(X) -> X > 8 end, L)]),
    io:format("~p~n", [lists:takewhile(fun(X) -> X > 2 end, L)]),
    io:format("~p~n", [lists:dropwhile(fun(X) -> X > 2 end, L)]),
    io:format("~p~n", [lists:foldr(fun(X, Acc) -> [X * 2 | Acc] end, [], L)]),
    io:format("~p~n", [lists:mapfoldl(fun(X, Acc) -> {X + 1, Acc + X} end, 0, [1, 2, 3])]),
    io:format("~p~n", [lists:flatmap(fun(X) -> [X, X] end, [1, 2])]),
    io:format("~p~n", [lists:enumerate([a, b])]),
    io:format("~p~n", [lists:filtermap(fun(X) when X > 4 -> {true, X * 10}; (_) -> false end, L)]),
    io:format("~p~n", [lists:delete(8, L)]),
    io:format("~p~n", [lists:sort([{b, 2}, {a, 1}, {b, 1}, "str", 3.0, 2, atom])]),
    io:format("~p~n", [length(lists:seq(1, 100000))]),
    ok.
